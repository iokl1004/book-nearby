import { describe, expect, it } from 'vitest'
import { cleanText, parseOperatingTime } from './operating-time.js'

describe('정보나루 운영시간 글자 해석', () => {
  // 서울 도서관 실제 값에서 뽑은 예시
  it.each([
    ['평일 09:00~22:00 / 주말 09:00~18:00', ['09:00', '22:00'], ['09:00', '18:00']],
    ['평일 09:00~22:00, 주말 09:00~18:00', ['09:00', '22:00'], ['09:00', '18:00']],
    ['평일 - 09:00~22:00, 주말 - 09:00~17:00', ['09:00', '22:00'], ['09:00', '17:00']],
    ['평일: 09시-22시 주말: 09시-18시', ['09:00', '22:00'], ['09:00', '18:00']],
    ['평일 : 9시 ~ 18시 / 주말 9시 ~17시', ['09:00', '18:00'], ['09:00', '17:00']],
    ['평일 오전 9시~오후 10시, 주말 오전 9시~오후5시', ['09:00', '22:00'], ['09:00', '17:00']],
    ['평일/주말 09:00~18:00', ['09:00', '18:00'], ['09:00', '18:00']],
    ['주중 : 09시~22시 주말 : 09시~18시', ['09:00', '22:00'], ['09:00', '18:00']],
  ])('%s', (text, weekday, weekend) => {
    expect(parseOperatingTime(text)).toEqual({ weekday, weekend })
  })

  it.each([
    '자료실(평일 09:00~22:00, 주말 09:00~18:00), 열람실(평일/주말 07:00~22:00)', // 공간마다 다름
    '평일 : 9시 ~ 18시 (종합자료실 22시까지) / 주말 9시 ~17시',
    '09:00 ~ 18:00', // 평일인지 주말인지 알 수 없음
    '평일 09:00 ~ 18:00', // 주말 정보 없음
    '',
  ])('애매한 글은 해석하지 않는다: %s', (text) => {
    expect(parseOperatingTime(text)).toBeNull()
  })

  it('HTML 문자를 바꾸고 의미 없는 값은 비운다', () => {
    expect(cleanText('토&middot;일: 09:00~18:00')).toBe('토·일: 09:00~18:00')
    expect(cleanText('-')).toBe('')
    expect(cleanText(undefined)).toBe('')
  })
})
