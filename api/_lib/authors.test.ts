import { describe, expect, it } from 'vitest'
import { parseAuthors, parseGenre } from './authors.js'

// 정보나루 실제 저자 글자
describe('저자 글자를 역할별로 나누기', () => {
  it.each([
    ['강민경 글 ;이영림 그림', { 글: ['강민경'], 그림: ['이영림'] }],
    ['글: 정상민,주성윤', { 글: ['정상민', '주성윤'] }],
    ['김강현 (지은이), 김기수 (그림)', { 그림: ['김기수'], 저자: ['김강현'] }],
    ['글·그림: 박시백', { 글: ['박시백'], 그림: ['박시백'] }],
    ['조앤 K. 롤링 저;최인자 옮김', { 저자: ['조앤 K. 롤링'], 옮김: ['최인자'] }],
    ['조앤 K. 롤링 지음;최인자 [공]옮김', { 저자: ['조앤 K. 롤링'], 옮김: ['최인자'] }],
    ['로버트 먼치', { 저자: ['로버트 먼치'] }],
    ['해성이앤피 편집부 (지은이)', { 저자: ['해성이앤피 편집부'] }],
    ['글: 이근 ;그림: 극동만화연구소', { 글: ['이근'], 그림: ['극동만화연구소'] }],
    ['도기성 (지은이), 지제근 (감수)', { 저자: ['도기성'], 감수: ['지제근'] }],
    ['글·그림: 미야니시 타츠야 ;옮김: 계일', { 글: ['미야니시 타츠야'], 그림: ['미야니시 타츠야'], 옮김: ['계일'] }],
    ['지은이: 폴 베리 ;옮긴이: 강권학', { 저자: ['폴 베리'], 옮김: ['강권학'] }],
    ['천인국,최자영 지음', { 저자: ['천인국', '최자영'] }],
    ['에마뉘엘 보두엥,홍은주 옮김', { 저자: ['에마뉘엘 보두엥'], 옮김: ['홍은주'] }],
    ['글: 설민석,그림: 김덕영', { 글: ['설민석'], 그림: ['김덕영'] }],
    ['원작: 흔한남매 ;그림: 유난희', { 그림: ['유난희'], 원작: ['흔한남매'] }],
    ['스테파니 로스 시슨 글·그림 ;이충호 옮김', { 글: ['스테파니 로스 시슨'], 그림: ['스테파니 로스 시슨'], 옮김: ['이충호'] }],
    ['정완영 [지음];임종길 그림', { 그림: ['임종길'], 저자: ['정완영'] }],
    ['글 그림: 김지현', { 글: ['김지현'], 그림: ['김지현'] }],
    ['세다드 카이드-살라 페론 (지은이), 에두아르드 알타리바 (그림), 이충호 (옮긴이)', { 그림: ['에두아르드 알타리바'], 저자: ['세다드 카이드-살라 페론'], 옮김: ['이충호'] }],
    ['헤르만 헤세 원작 ;박승원 그림', { 그림: ['박승원'], 원작: ['헤르만 헤세'] }],
    ['저자: 올드스테어즈 편집부', { 저자: ['올드스테어즈 편집부'] }],
  ])('%s', (raw, expected) => {
    const result = Object.fromEntries(parseAuthors(raw).map((c) => [c.role, c.names]))
    expect(result).toEqual(expected)
  })

  it('항상 글 → 그림 → 저자 → 원작 → 옮김 → 감수 순서', () => {
    expect(parseAuthors('이충호 (옮긴이), 에두아르드 알타리바 (그림), 세다드 (지은이)').map((c) => c.role)).toEqual(['그림', '저자', '옮김'])
  })

  it('빈 값은 빈 목록', () => {
    expect(parseAuthors('')).toEqual([])
  })
})

describe('주제 분류', () => {
  it.each([
    ['문학 > 한국문학 > 소설', '문학 › 소설'],
    ['역사 > 아시아(아세아) > 한국', '역사 › 한국'],
    ['자연과학 > 자연과학 > 자연과학', '자연과학'],
    ['문학 > 문학 > 전집, 총서', '문학 › 전집, 총서'],
    ['null > null > null', ''],
    ['', ''],
  ])('%s → %s', (raw, expected) => {
    expect(parseGenre(raw)).toBe(expected)
  })
})
